import React from 'react';
import { createRoot } from 'react-dom/client';
import './styles.css';
import App from './App';
import GlobalWheelWindow from './GlobalWheelWindow';
import ImageToolHost from './ImageToolHost';
const root = createRoot(document.getElementById('root')!);
const isGlobalWheel = new URLSearchParams(window.location.search).get('santara-wheel') === '1';
const isImageTool = new URLSearchParams(window.location.search).get('santara-image-tool') === '1';
if (isGlobalWheel) document.documentElement.classList.add('global-wheel-document');
if (isImageTool) document.documentElement.classList.add('image-tool-document');
root.render(<React.StrictMode>{isGlobalWheel ? <GlobalWheelWindow /> : isImageTool ? <ImageToolHost /> : <App />}</React.StrictMode>);
